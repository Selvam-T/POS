"""Generate PyInstaller and Inno Setup metadata without importing the application."""

import argparse
import ast
from pathlib import Path
import re
import sys


DEPLOYMENT_DIR = Path(__file__).resolve().parents[1]
GENERATED_DIR = DEPLOYMENT_DIR / 'generated'
DEFAULT_CONFIG = DEPLOYMENT_DIR.parent / 'Development' / 'src' / 'config.py'
REQUIRED = ('APP_VERSION', 'DEVELOPER_NAME')


def read_metadata(config_path):
    tree = ast.parse(config_path.read_text(encoding='utf-8-sig'), filename=str(config_path))
    values = {}
    for node in tree.body:
        if isinstance(node, ast.Assign):
            names = [target.id for target in node.targets if isinstance(target, ast.Name)]
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            names = [node.target.id]
        else:
            continue
        for name in names:
            if name not in REQUIRED:
                continue
            if name in values:
                raise ValueError(f'{name} must be assigned exactly once')
            try:
                value = ast.literal_eval(node.value)
            except (ValueError, TypeError) as exc:
                raise ValueError(f'{name} must be a literal string') from exc
            if not isinstance(value, str) or not value.strip():
                raise ValueError(f'{name} must be a nonempty string')
            if any(ord(char) < 32 for char in value):
                raise ValueError(f'{name} must not contain control characters')
            values[name] = value
    for name in REQUIRED:
        if name not in values:
            raise ValueError(f'Missing {name} in {config_path}')
    version = values['APP_VERSION']
    if not re.fullmatch(r'(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)\.(0|[1-9][0-9]*)', version):
        raise ValueError('APP_VERSION must be major.minor.patch (for example 1.2.3)')
    parts = tuple(int(part) for part in version.split('.'))
    if any(part > 65535 for part in parts):
        raise ValueError('Each APP_VERSION component must be between 0 and 65535')
    return values, parts + (0,)


def render_windows(values, numeric_version):
    fields = {
        'CompanyName': values['DEVELOPER_NAME'],
        'FileDescription': 'SelvamPOS point of sale application',
        'FileVersion': values['APP_VERSION'],
        'InternalName': 'SelvamPOS',
        'OriginalFilename': 'SelvamPOS.exe',
        'ProductName': 'SelvamPOS',
        'ProductVersion': values['APP_VERSION'],
        'Comments': f"Developed by {values['DEVELOPER_NAME']}",
    }
    strings = ',\n'.join(f'          StringStruct({key!r}, {value!r})' for key, value in fields.items())
    return f'''# UTF-8
# Generated by generate_version_info.py from Development/src/config.py. Do not edit.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={numeric_version!r},
    prodvers={numeric_version!r},
    mask=0x3f, flags=0x0, OS=0x40004, fileType=0x1,
    subtype=0x0, date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable('040904B0', [
{strings}
      ])
    ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
'''


def render_installer(values):
    # ISPP string literals escape embedded quotes by doubling them.
    def quote(value):
        return '"' + value.replace('"', '""') + '"'

    return '; Generated by generate_version_info.py. Do not edit.\n' + '\n'.join(
        f'#define {name} {quote(values[key])}'
        for name, key in (
            ('MyAppVersion', 'APP_VERSION'),
            ('MyAppPublisher', 'DEVELOPER_NAME'),
            ('MyAppDeveloper', 'DEVELOPER_NAME'),
        )
    ) + '\n'


def generate(config_path, output_dir):
    values, numeric_version = read_metadata(config_path)
    outputs = {
        'version_info.txt': render_windows(values, numeric_version),
        'version_info.iss': render_installer(values),
    }
    output_dir.mkdir(parents=True, exist_ok=True)
    for name, content in outputs.items():
        target = output_dir / name
        temporary = target.with_suffix(target.suffix + '.tmp')
        try:
            temporary.write_text(content, encoding='utf-8', newline='\n')
            temporary.replace(target)
        finally:
            temporary.unlink(missing_ok=True)
    return values['APP_VERSION']


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--config', type=Path, default=DEFAULT_CONFIG)
    parser.add_argument('--output-dir', type=Path, default=GENERATED_DIR)
    args = parser.parse_args(argv)
    try:
        version = generate(args.config, args.output_dir)
    except (OSError, ValueError, SyntaxError) as exc:
        print(f'Version metadata generation failed: {exc}', file=sys.stderr)
        return 1
    print(f'Generated executable and installer metadata for SelvamPOS {version}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
